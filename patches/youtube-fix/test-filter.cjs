const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const script = fs.readFileSync(__dirname + '/filter.js', 'utf8');
const ctx = vm.createContext({location:{hostname:'www.youtube.com',pathname:'/tv'},document:{title:''}});
vm.runInContext('window=globalThis', ctx);
vm.runInContext(script, ctx);
const input = JSON.stringify({playerAds:[{}],adPlacements:[{}],streamingData:{formats:[{url:'https://media.example/video'}]},items:[{adSlotRenderer:{}},{videoRenderer:{title:'Video'}}]});
ctx.input = input;
const output = JSON.parse(vm.runInContext('JSON.stringify(JSON.parse(input))', ctx));
assert.equal(output.playerAds, undefined);
assert.equal(output.adPlacements, undefined);
assert.equal(output.streamingData.formats[0].url, 'https://media.example/video');
assert.deepEqual(output.items, [{videoRenderer:{title:'Video'}}]);
assert.equal(vm.runInContext('JSON.parse(\'{"n":2}\', (key,value)=>key==="n"?value*3:value).n',ctx),6);
assert.throws(()=>vm.runInContext('JSON.parse("broken")',ctx));
const original = vm.runInContext('JSON.parse',ctx);
vm.runInContext(script,ctx);
assert.equal(vm.runInContext('JSON.parse',ctx),original);
const elsewhere = vm.createContext({location:{hostname:'example.com',pathname:'/tv'},document:{title:''}});
vm.runInContext('window=globalThis',elsewhere);
vm.runInContext(script,elsewhere);
assert.equal(vm.runInContext('typeof __ytFixAds',elsewhere),'undefined');
console.log('Response filtering, normal video, reviver, errors, reinjection and origin checks passed');
